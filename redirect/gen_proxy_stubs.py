#!/usr/bin/env python3
"""Generate the export surface of a proxy named after a real System32 DLL.

    gen_proxy_stubs.py <System32 dll> <out.def> <out.inc>

A .def forwarder (`Name=other.Name`) can only name a module, never a full path, and the real DLL must come from
System32 (nothing is renamed or added beside the game). So every export of the real DLL becomes a tiny jump stub
`coop_fwd_<i>` that jumps through a table. A table slot starts at a resolver stub that loads the real export with
`original_system_export` (full System32 path), stores it and jumps to it with the caller's arguments intact.
The output depends only on the real DLL's export table; the build uses the committed files, and
test_gen_proxy_stubs.py regenerates them from the live DLL when it exists.
"""
import re
import sys
from pathlib import Path

from pe_loader import inspect

SAFE = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')


def exports_of(path):
    exports = sorted(inspect(path)['exports'], key=lambda e: e['ordinal'])
    if not exports:
        raise ValueError('no exports')
    for e in exports:
        if not e['name'] or not SAFE.match(e['name']):
            raise ValueError(f"export {e} needs explicit review (unnamed or unusual name)")
    return exports


def render_def(dll_name, exports):
    lines = [f'LIBRARY {dll_name}', 'EXPORTS']
    lines += [f"  {e['name']}=coop_fwd_{i} @{e['ordinal']}" for i, e in enumerate(exports)]
    return '\n'.join(lines) + '\n'


def render_inc(dll_name, exports):
    n = len(exports)
    out = [f'// Generated by gen_proxy_stubs.py from the export table of System32\\{dll_name}.dll. Do not edit.',
           f'#define COOP_PROXY_DLL L"{dll_name}.dll"',
           f'#define COOP_PROXY_EXPORTS {n}',
           'static const char* const coop_export_names[COOP_PROXY_EXPORTS]={']
    out += [f'    "{e["name"]}",' for e in exports]
    out += ['};', 'asm(', '    ".intel_syntax noprefix\\n"', '    ".text\\n"']
    for i in range(n):
        out.append(f'    ".globl coop_fwd_{i}\\n coop_fwd_{i}: jmp qword ptr [rip+coop_fwd_table+{8 * i}]\\n"')
    for i in range(n):
        out.append(f'    "coop_slow_{i}: mov eax,{i}\\n jmp coop_slow_common\\n"')
    out += [
        '    "coop_slow_common:\\n"',
        '    " push rcx\\n push rdx\\n push r8\\n push r9\\n sub rsp,0x68\\n"',
        '    " movdqu [rsp+0x20],xmm0\\n movdqu [rsp+0x30],xmm1\\n movdqu [rsp+0x40],xmm2\\n movdqu [rsp+0x50],xmm3\\n"',
        '    " mov ecx,eax\\n call coop_resolve\\n"',
        '    " movdqu xmm0,[rsp+0x20]\\n movdqu xmm1,[rsp+0x30]\\n movdqu xmm2,[rsp+0x40]\\n movdqu xmm3,[rsp+0x50]\\n"',
        '    " add rsp,0x68\\n pop r9\\n pop r8\\n pop rdx\\n pop rcx\\n jmp rax\\n"',
        '    ".data\\n .balign 8\\n coop_fwd_table:\\n"']
    out += [f'    " .quad coop_slow_{i}\\n"' for i in range(n)]
    out += ['    ".text\\n .att_syntax\\n"', ');', '']
    return '\n'.join(out)


def main(argv):
    dll, out_def, out_inc = argv[1:4]
    name = Path(dll).stem.lower()
    exports = exports_of(dll)
    Path(out_def).write_text(render_def(name, exports))
    Path(out_inc).write_text(render_inc(name, exports))
    print(f'{name}: {len(exports)} exports')


if __name__ == '__main__':
    main(sys.argv)
