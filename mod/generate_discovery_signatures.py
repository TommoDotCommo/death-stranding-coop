"""Keep the C++ discovery patterns identical to the reviewed Python scanner."""
from pathlib import Path
import sys
from find_signatures import CANDIDATES
lines = ['// Generated by generate_discovery_signatures.py; do not edit.', '#pragma once',
         'inline std::vector<Candidate> candidates() { return {']
for c in CANDIDATES:
    refs = ','.join('{"%s",%d,%d}' % (r.name, r.instruction, r.length) for r in c.refs)
    lines.append('{"%s","%s",{%s}},' % (c.name, c.pattern, refs))
lines.append('}; }\n')
result = '\n'.join(lines)
p = Path(__file__).with_name('discovery_signatures.h')
if '--write' in sys.argv: p.write_text(result)
elif not p.exists() or p.read_text() != result: sys.exit('discovery signatures stale')
