#!/usr/bin/env python3
"""Pinned mod build hash: first 128 bits of SHA-256 over named production sources.

Run --write after an intentional core change; normal builds only verify the pin.
Exclude generated header to avoid self reference. Adapter builds must extend this
manifest to cover their own production sources before in-process use.
"""
import hashlib
from pathlib import Path
import sys
root = Path(__file__).resolve().parent
h = hashlib.sha256()
for name in ('core.h', 'core.cpp'):
    data = (root / name).read_bytes()
    h.update(name.encode() + b'\0' + len(data).to_bytes(8, 'little') + data)
identity = h.digest()[:16]
text = ('// Generated by build_id.py --write; do not edit.\n#pragma once\n'
        '#include <array>\n#include <cstdint>\nnamespace ds {\n'
        'constexpr std::array<uint8_t,16> ModBuild = {' +
        ','.join(f'0x{b:02x}' for b in identity) + '};\n}\n')
path = root / 'build_id.h'
if sys.argv[1:] == ['--write']:
    path.write_text(text)
elif not path.exists() or path.read_text() != text:
    sys.exit('stale mod build hash: run python3 build_id.py --write after reviewing the source change')
print('mod_build_sha256_128=' + identity.hex())
